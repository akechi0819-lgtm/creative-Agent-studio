import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {readDna, saveDna} from '../src/dna/profile.mjs';
import {createTask, readTask, confirmInputs, setSheet, confirmSheet, applyDna} from '../src/creative/tasks.mjs';
test('DNA defaults off, saves explicitly, and never rewrites confirmed tasks', async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'studio-dna-'));
  t.after(() => fs.rm(root, {recursive:true, force:true}));
  assert.equal((await readDna({root})).enabled, false);
  await assert.rejects(saveDna({enabled:true,content:'语气克制',by:'Codex Agent',note:'自动保存',expectedRevision:1},{root}), /人工保存依据/);
  const first = await saveDna({enabled:true,content:'语气克制',by:'张三（AI运营负责人）',note:'明确保存',expectedRevision:1},{root});
  assert.equal(first.by, '张三（AI运营负责人）');
  let task = await createTask({title:'测试',brief:'新海报'},root);
  task = await confirmInputs(task.id,{revision:task.revision,by:'用户',note:'确认需求与DNA'}, {root});
  task = await setSheet(task.id,{title:'海报',pages:[{page:1,copy:'标题',prompt:'语气克制',size:'3:4'}]}, {root,expectedRevision:task.revision,inputRevision:task.inputConfirmation.revision});
  task = await confirmSheet(task.id,{version:1,by:'用户',note:'确认'}, {root,expectedRevision:task.revision});
  const old = structuredClone(task);
  const next = await saveDna({enabled:true,content:'活泼',by:'用户',note:'明确改动',expectedRevision:first.revision}, {root});
  assert.deepEqual(await readTask(task.id,root),old);
  await assert.rejects(applyDna(task.id,{dnaRevision:first.revision},{root,expectedRevision:task.revision}), /版本已变化/);
  task = await applyDna(task.id,{dnaRevision:next.revision},{root,expectedRevision:task.revision});
  assert.equal(task.inputConfirmation,null);
  assert.equal(task.sheetConfirmation,null);
  assert.equal(task.dna.content,'活泼');
  assert.equal(task.sheets[0].inputs.dna.content,'语气克制');
  await assert.rejects(saveDna({enabled:false,content:'',by:'用户',note:'保存',expectedRevision:1},{root}),/版本已更新/);
  await assert.rejects(saveDna({enabled:true,content:'',by:'用户',note:'保存',expectedRevision:next.revision},{root}),/为空/);
});

test('旧任务可显式应用关闭版 DNA；全局关闭不静默修改任务且仍校验版本', async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'studio-dna-disable-'));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  const enabled = await saveDna({ enabled: true, content: '保留这份偏好草稿', by: '用户', note: '明确启用', expectedRevision: 1 }, { root });
  let task = await createTask({ title: '旧任务停用 DNA', brief: '隔离合同测试' }, root);
  task = await confirmInputs(task.id, { revision: task.revision, by: '用户', note: '确认启用版快照' }, { root });
  task = await setSheet(task.id, { title: '旧制作单', pages: [{ page: 1, copy: '标题', prompt: '使用当前偏好', size: '3:4' }] }, { root, expectedRevision: task.revision, inputRevision: task.inputConfirmation.revision });
  task = await confirmSheet(task.id, { version: task.sheetVersion, by: '用户', note: '明确确认旧制作单' }, { root, expectedRevision: task.revision });
  const previous = structuredClone(task);
  const disabled = await saveDna({ enabled: false, content: enabled.content, by: '用户', note: '明确关闭全局 DNA', expectedRevision: enabled.revision }, { root });
  assert.deepEqual(await readTask(task.id, root), previous, '全局关闭不静默改动旧任务');
  await assert.rejects(applyDna(task.id, { dnaRevision: disabled.revision }, { root, expectedRevision: task.revision - 1 }), /版本冲突/);
  assert.deepEqual(await readTask(task.id, root), previous);
  task = await applyDna(task.id, { dnaRevision: disabled.revision }, { root, expectedRevision: task.revision });
  assert.equal(task.dna.revision, disabled.revision);
  assert.equal(task.dna.enabled, false);
  assert.equal(task.dna.content, '');
  assert.equal(task.inputConfirmation, null);
  assert.equal(task.sheetConfirmation, null);
  assert.equal(task.finalApproval, null);
  assert.deepEqual(task.sheets, previous.sheets, '旧制作单和其启用版 DNA 快照保留');
  assert.equal(task.sheets[0].inputs.dna.content, enabled.content);
  assert.equal((await readDna({ root })).content, enabled.content, '停用任务不删除全局草稿');
});
