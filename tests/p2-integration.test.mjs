import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import {unzipSync} from 'fflate';
import {importAsset,cleanAsset,editAsset,confirmAsset,deleteAsset,readAsset,queryAssets} from '../src/assets/library.mjs';
import {createTask,setAssetSources,confirmInputs,setSheet,confirmSheet,readTask,withTask,recordReview,approveFinal,exportTask,taskDirectory} from '../src/creative/tasks.mjs';

test('clean-review-confirm-search-task snapshot survives source edits, deletion and backup', async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(),'studio-p2-flow-'));
  t.after(()=>fs.rm(root,{recursive:true,force:true}));
  const original = path.join(root,'source.txt');
  await fs.writeFile(original,'测试原件正文。历史价格100元仅属于去年。');
  let asset = await importAsset({title:'历史图文',body:'原文',files:[{path:original}],source:{kind:'historical-reference'}},{root});
  await assert.rejects(confirmAsset(asset.id,{by:'用户',note:'尚未清洗'},{root,expectedRevision:asset.revision}));
  assert.equal((await queryAssets({}, {root})).length,0);
  const cleaner=async input=>({...input,summary:'历史内容结构参考',tags:['小红书','知识图文'],fileResults:[{name:'source.txt',text:'测试原件正文。历史价格100元仅属于去年。'}],promptVersion:'fixture'});
  asset = await cleanAsset(asset.id,{root,expectedRevision:asset.revision,cleaner});
  assert.equal(asset.status,'needs_review');
  assert.equal((await queryAssets({}, {root})).length,0);
  asset=await editAsset(asset.id,{tags:['小红书','内容参考']},{root,expectedRevision:asset.revision});
  asset=await confirmAsset(asset.id,{by:'用户',note:'测试夹具人工微调后入库'},{root,expectedRevision:asset.revision});
  assert.equal((await queryAssets({tags:['小红书'],query:'历史价格'},{root})).length,1);
  let task=await createTask({title:'引用测试',brief:'只借鉴结构'},root);
  const selections=[{assetId:asset.id,assetRevision:asset.revision,decision:'retained',purpose:'结构参考',factBoundary:'历史价格不可用于当前业务'}];
  await assert.rejects(setAssetSources(task.id,[{...selections[0],assetRevision:asset.revision-1}],{root,expectedRevision:task.revision}),/版本已变化/);
  task=await setAssetSources(task.id,selections,{root,expectedRevision:task.revision});
  assert.equal(task.sources[0].tags.includes('内容参考'),true);
  assert.equal(task.sources[0].extractions[0].text.includes('历史价格'),true);
  const frozen=structuredClone(task.sources);
  asset=await editAsset(asset.id,{tags:['已修改']},{root,expectedRevision:asset.revision});
  await deleteAsset(asset.id,{root,expectedRevision:asset.revision});
  assert.deepEqual((await readTask(task.id,root)).sources,frozen);
  assert.equal(await fs.readFile(path.join(taskDirectory(task.id,root),frozen[0].files[0].relativePath),'utf8'),await fs.readFile(original,'utf8'));
  task=await confirmInputs(task.id,{revision:task.revision,by:'用户',note:'测试夹具确认历史事实边界'},{root});
  task=await setSheet(task.id,{title:'测试单页',sourceIds:[asset.id],pages:[{page:1,copy:'新文案',prompt:'fixture',size:'3:4',sourceIds:[asset.id]}]},{root,expectedRevision:task.revision,inputRevision:task.inputConfirmation.revision});
  task=await confirmSheet(task.id,{version:1,by:'用户',note:'测试夹具确认制作单'},{root,expectedRevision:task.revision});
  const imagePath=path.join(root,'fixture.png');const image=Buffer.from('fixture image');await fs.writeFile(imagePath,image);const sha256=crypto.createHash('sha256').update(image).digest('hex');
  task=await withTask(task.id,draft=>{draft.execution={version:1,status:'succeeded',pages:[{page:1,status:'succeeded',image:{path:imagePath,sha256}}]};},{root,expectedRevision:task.revision});
  task=await recordReview(task.id,{page:1,sha256,decision:'pass',reviewer:'测试人工',notes:'模拟夹具审核，非真实成品验收'},{root,expectedRevision:task.revision});
  task=await approveFinal(task.id,{version:1,images:[{page:1,sha256}],by:'测试人工',note:'模拟夹具批准'},{root,expectedRevision:task.revision});
  const exported=await exportTask(task.id,{root,expectedRevision:task.revision});
  const archive=unzipSync(await fs.readFile(path.join(taskDirectory(task.id,root),exported.export.archiveRelativePath)));
  assert.equal(Buffer.from(archive[frozen[0].files[0].relativePath]).toString(),await fs.readFile(original,'utf8'));
  const manifest=JSON.parse(Buffer.from(archive['manifest.json']).toString());
  assert.equal(manifest.files.some(file=>file.path===frozen[0].files[0].relativePath),true);
  const restored=path.join(root,'restored');
  await fs.cp(path.join(root,'assets'),path.join(restored,'assets'),{recursive:true});
  const backup=await readAsset(asset.id,{root:restored});
  assert.equal(backup.status,'deleted');
  assert.equal(backup.history.some(record=>record.state.tags.includes('内容参考')),true);
});
