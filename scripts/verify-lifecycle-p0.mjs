import { spawnSync } from 'node:child_process';
import { readFile, writeFile, access } from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import { root, connection, health } from '../src/canvas/client.mjs';
const prior=await connection();await health(prior);
const data=path.join(root,'.p0-state/lifecycle');
const env={...process.env,STUDIO_DATA_DIR:data,STUDIO_PROJECT_ID:'p0-lifecycle'};
const run=action=>spawnSync(process.execPath,[path.join(root,'scripts/canvas.mjs'),action],{cwd:root,env,encoding:'utf8'});
let result=run('start');assert.equal(result.status,0,result.stderr);
const first=JSON.parse(await readFile(path.join(data,'canvas-instance.json'),'utf8'));
assert.notEqual(first.instanceId,prior.instanceId);assert.notEqual(first.webUrl,prior.webUrl);assert.notEqual(first.bridgeUrl,prior.bridgeUrl);
result=run('start');assert.equal(result.status,1);assert.match(result.stderr,/已运行/);
result=run('stop');assert.equal(result.status,0,result.stderr);
for(let i=0;i<100;i++){if(await access(path.join(data,'supervisor.lock')).then(()=>false).catch(()=>true))break;await new Promise(r=>setTimeout(r,50));}
assert.equal(await access(path.join(data,'supervisor.lock')).then(()=>true).catch(()=>false),false);
assert.equal(await access(path.join(data,'bridge/canvas-agent.lock')).then(()=>true).catch(()=>false),false);
await health(prior);
result=run('start');assert.equal(result.status,0,result.stderr);
const second=JSON.parse(await readFile(path.join(data,'canvas-instance.json'),'utf8'));assert.notEqual(second.instanceId,first.instanceId);assert.equal(second.webUrl,first.webUrl);
result=run('stop');assert.equal(result.status,0,result.stderr);
await health(prior);
const evidence={result:'passed',tests:['second-independent-instance','distinct-dynamic-ports','duplicate-start-rejected','owned-process-stop','lock-release','bridge-signal-lock-release','restart-new-identity','stable-web-origin-on-restart','prior-instance-unaffected'],priorInstance:prior.instanceId,firstInstance:first.instanceId,secondInstance:second.instanceId};
await writeFile(path.join(root,'docs/evidence/p0/lifecycle-report.json'),JSON.stringify(evidence,null,2));console.log(JSON.stringify(evidence));
