import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {chromium} from 'playwright';
import {listenStudioServer} from '../src/web/server.mjs';
import {startModelPlugin} from '../adapters/free-model/service.mjs';
import {saveConfig,readConfigRecord} from '../src/web/config.mjs';
const root=await fs.mkdtemp(path.join(os.tmpdir(),'studio-plugin-ui-'));
const evidence=path.resolve('docs/evidence/model-plugin');
await fs.mkdir(evidence,{recursive:true});
let app,plugin,browser;const errors=[];const realFetch=globalThis.fetch;
try{
 await saveConfig({expectedRevision:1,base:{baseUrl:'https://fixture.invalid/v1',model:'fixture-own',apiKey:'fixture-private-key'},image:{baseUrl:'https://image.invalid/v1',model:'fixture-image',apiKey:'fixture-image-private-key'}},{root});
 globalThis.fetch=async(url,init)=>new URL(url).hostname==='127.0.0.1'?realFetch(url,init):Response.json({data:[{id:'fixture/free',isFree:true,name:'Fixture Free',architecture:{input_modalities:['image']}}]});
 plugin=await startModelPlugin({root});app=await listenStudioServer({root,port:0});
 browser=await chromium.launch({channel:'chrome',headless:true});const page=await browser.newPage({viewport:{width:1440,height:1050}});page.on('pageerror',e=>errors.push(e.message));
 await page.goto(`http://127.0.0.1:${app.address.port}`,{waitUntil:'networkidle'});
 await page.getByRole('button',{name:'模型与服务',exact:true}).click();
 await page.getByLabel('基础模型来源').selectOption('kilo');
 const card=page.locator('.provider-card').first();
 assert.equal(await card.getByLabel('服务地址').count(),0);
 await card.getByRole('button',{name:'获取模型',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('.provider-card select[aria-label]')?.options.length>1);
 await card.locator('select[aria-label]').selectOption('kilo/fixture/free');
 await page.getByRole('button',{name:'保存配置',exact:true}).click();
 await page.getByText('配置已保存。密钥不会再次显示。',{exact:true}).waitFor();
 const saved=await readConfigRecord({root});assert.equal(saved.base.source,'kilo');assert.equal(saved.base.apiKey,'fixture-private-key');assert.equal(saved.image.model,'fixture-image');
 await page.screenshot({path:path.join(evidence,'kilo-desktop.png'),fullPage:true});
 await page.getByRole('button',{name:'使用自己的 API',exact:true}).click();
 assert.equal(await card.getByLabel('服务地址').inputValue(),'https://fixture.invalid/v1');
 assert.equal(await card.getByLabel('API 密钥').count(),1);
 await page.screenshot({path:path.join(evidence,'custom-desktop.png'),fullPage:true});
 await page.getByLabel('基础模型来源').selectOption('opencode');
 await page.getByText('OpenCode 当前实测不可用：上游限制第三方客户端；建议选择 Kilo。',{exact:true}).waitFor();
 await page.getByLabel('基础模型来源').selectOption('workbuddy-cn');
 await page.getByText('此区域还没有登录账号。',{exact:true}).waitFor();
 assert.equal(await card.getByRole('button',{name:'获取模型',exact:true}).isDisabled(),true);
 await page.screenshot({path:path.join(evidence,'workbuddy-desktop.png'),fullPage:true});
 await page.setViewportSize({width:390,height:844});
 const closeNav=page.getByRole('button',{name:'收起导航栏',exact:true});
 if(await closeNav.isVisible()) await closeNav.click();
 await page.waitForFunction(()=>document.querySelector('.sidebar').getBoundingClientRect().right<=0);
 await page.screenshot({path:path.join(evidence,'workbuddy-mobile.png')});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 assert.deepEqual(errors,[]);
 await fs.writeFile(path.join(evidence,'ui-report.json'),JSON.stringify({time:new Date().toISOString(),isolated:true,externalRequests:0,checks:['managed-source-save','custom-key-preserved','image-config-separate','opencode-unavailable-notice','workbuddy-login-required','desktop-mobile-no-overflow'],errors},null,2));
 console.log('Model plugin browser verification passed; isolated profile, no external requests.');
}finally{globalThis.fetch=realFetch;await browser?.close();await app?.close();await plugin?.close();await fs.rm(root,{recursive:true,force:true});}
